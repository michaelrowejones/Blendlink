export function componentDefinition(type: string): PortableComponentDefinition | undefined {
  return CORE_COMPONENT_REGISTRY[type]
}

export function componentDefaults(type: string): JsonObject | undefined {
  const definition = componentDefinition(type)
  if (!definition) return undefined
  const values: Record<string, JsonValue> = {}
  for (const [name, field] of Object.entries(definition.fields)) values[name] = field.default
  return values
}

/** Parse without erasing a vendor component. Errors reject malformed records;
 * a well-formed unknown namespace becomes a warning and remains available to
 * its future website adapter. */
export function parsePortableComponents(value: unknown): ParsePortableComponentsResult {
  const diagnostics: ComponentDiagnostic[] = []
  if (value === undefined) return { components: [], diagnostics }
  if (!Array.isArray(value)) {
    return { components: [], diagnostics: [{ severity: 'error', path: 'components', message: 'components must be a list' }] }
  }
  const components: PortableComponentRecord[] = []
  const ids = new Set<string>()
  const placements = new Set<string>()
  const websiteSurfaceNames = new Set<string>()
  for (const [index, raw] of value.entries()) {
    const path = `components[${index}]`
    if (!isRecord(raw)) {
      diagnostics.push({ severity: 'error', path, message: 'component must be an object' })
      continue
    }
    const id = stringValue(raw.id)
    const type = stringValue(raw.type)
    const schemaVersion = raw.schemaVersion
    const enabled = raw.enabled
    const target = parseTarget(raw.target, `${path}.target`, diagnostics)
    const values = raw.values
    let valid = true
    if (!isStableId(id)) {
      diagnostics.push({ severity: 'error', path: `${path}.id`, message: 'component id must be a non-empty stable identifier' })
      valid = false
    } else if (ids.has(id)) {
      diagnostics.push({ severity: 'error', path: `${path}.id`, message: `duplicate component id "${id}"` })
      valid = false
    }
    ids.add(id)
    if (!isComponentType(type)) {
      diagnostics.push({ severity: 'error', path: `${path}.type`, message: 'component type must be a vendor-namespaced identifier' })
      valid = false
    }
    if (schemaVersion !== PORTABLE_COMPONENT_SCHEMA_VERSION) {
      diagnostics.push({ severity: 'error', path: `${path}.schemaVersion`, message: `component schemaVersion must be ${PORTABLE_COMPONENT_SCHEMA_VERSION}` })
      valid = false
    }
    if (typeof enabled !== 'boolean') {
      diagnostics.push({ severity: 'error', path: `${path}.enabled`, message: 'component enabled must be boolean' })
      valid = false
    }
    if (!isJsonObject(values)) {
      diagnostics.push({ severity: 'error', path: `${path}.values`, message: 'component values must be a JSON object' })
      valid = false
    }
    if (!target) valid = false
    if (!valid || !target || !isJsonObject(values) || typeof enabled !== 'boolean') continue
    const component: PortableComponentRecord = {
      id, type, schemaVersion: PORTABLE_COMPONENT_SCHEMA_VERSION, enabled, target, values,
    }
    const definition = componentDefinition(type)
    const placement = definition?.cardinality === 'one-per-scene'
      ? `${type}\u0000scene`
      : `${type}\u0000${target.kind === 'scene' ? 'scene' : target.objectId}`
    if (placements.has(placement)) {
      diagnostics.push({
        severity: 'error', path,
        message: definition?.cardinality === 'one-per-scene'
          ? `component "${type}" is already assigned in this scene`
          : `component "${type}" is already assigned to this target`,
      })
    }
    placements.add(placement)
    if (!definition) {
      diagnostics.push({ severity: 'warning', path: `${path}.type`, message: `component "${type}" requires a website adapter; preserved unchanged` })
    } else {
      validateCoreComponent(component, definition, path, diagnostics)
    }
    if (component.type === 'blendlink.website-surface') {
      const name = component.values.name
      if (typeof name === 'string' && /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(name) && name.length <= 64) {
        if (websiteSurfaceNames.has(name)) {
          diagnostics.push({
            severity: 'error', path: `${path}.values.name`,
            message: `Website Surface name "${name}" is already used in this scene`,
          })
        }
        websiteSurfaceNames.add(name)
      }
    }
    components.push(component)
  }
  return { components, diagnostics }
}

function validateCoreComponent(
  component: PortableComponentRecord,
  definition: PortableComponentDefinition,
  path: string,
  diagnostics: ComponentDiagnostic[],
): void {
  if (!definition.targets.includes(component.target.kind)) {
    diagnostics.push({ severity: 'error', path: `${path}.target`, message: `${definition.label} targets ${definition.targets.join(' or ')}` })
  }
  for (const [name, value] of Object.entries(component.values)) {
    const field = definition.fields[name]
    if (!field) {
      diagnostics.push({ severity: 'warning', path: `${path}.values.${name}`, message: `unknown ${definition.label} field preserved for a newer adapter` })
      continue
    }
    validateField(value, field, `${path}.values.${name}`, diagnostics)
  }
  for (const [name, field] of Object.entries(definition.fields)) {
    if (component.enabled && field.required && (component.values[name] === undefined || (typeof component.values[name] === 'string' && !component.values[name].trim()))) {
      diagnostics.push({ severity: 'error', path: `${path}.values.${name}`, message: `${field.label} is required` })
    }
    if (field.kind === 'object-reference' && component.values[name] !== undefined && component.values[name] !== '' && !isStableId(component.values[name])) {
      diagnostics.push({ severity: 'error', path: `${path}.values.${name}`, message: `${field.label} must be a stable object ID` })
    }
  }
  if (component.type === 'blendlink.open-url') {
    validateComponentUrl(component.values.url, new Set(['http', 'https', 'mailto', 'tel']), `${path}.values.url`, diagnostics)
  } else if (component.type === 'blendlink.audio-source') {
    validateComponentUrl(component.values.url, new Set(['http', 'https']), `${path}.values.url`, diagnostics)
    const minimum = component.values.minDistance
    const maximum = component.values.maxDistance
    if (typeof minimum === 'number' && typeof maximum === 'number' && maximum <= minimum) {
      diagnostics.push({
        severity: 'error', path: `${path}.values.maxDistance`,
        message: 'Silent Beyond must be farther than Full Volume Within',
      })
    }
  } else if (component.type === 'blendlink.color-grading') {
    validateComponentUrl(component.values.lutUrl, new Set(['http', 'https']), `${path}.values.lutUrl`, diagnostics)
  } else if (component.type === 'blendlink.depth-of-field' && component.enabled && component.values.focusMode === 'object') {
    if (!isStableId(component.values.focusTargetId)) {
      diagnostics.push({
        severity: 'error', path: `${path}.values.focusTargetId`,
        message: 'Focus Object is required when Focus With is object',
      })
    }
  } else if (component.type === 'blendlink.chromatic-aberration' && component.enabled) {
    const amount = component.values.amount
    if (typeof amount === 'number' && amount > 0.01) {
      diagnostics.push({
        severity: 'warning', path: `${path}.values.amount`,
        message: 'Strong chromatic aberration can reduce readability; values at or below 0.01 are safer for most scenes',
      })
    }
  } else if (component.type === 'blendlink.pixelation') {
    const pixelSize = component.values.pixelSize
    if (typeof pixelSize === 'number' && Number.isFinite(pixelSize) && !Number.isInteger(pixelSize)) {
      diagnostics.push({
        severity: 'error', path: `${path}.values.pixelSize`,
        message: 'Pixel Size must be a whole number of CSS pixels',
      })
    }
  } else if (component.type === 'blendlink.website-surface') {
    const name = component.values.name
    if (typeof name === 'string' && (!/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(name) || name.length > 64)) {
      diagnostics.push({
        severity: 'error', path: `${path}.values.name`,
        message: 'Website Name must be lowercase kebab-case, up to 64 characters (for example monitor-screen)',
      })
    }
  }
}

function validateComponentUrl(
  value: JsonValue | undefined,
  allowedSchemes: ReadonlySet<string>,
  path: string,
  diagnostics: ComponentDiagnostic[],
): void {
  if (typeof value !== 'string' || !value.trim()) return
  const scheme = /^([a-z][a-z0-9+.-]*):/i.exec(value.trim())?.[1]?.toLowerCase()
  if (scheme && !allowedSchemes.has(scheme)) {
    diagnostics.push({
      severity: 'error', path,
      message: `URL scheme ${scheme}: is unsupported; use ${[...allowedSchemes].join(', ')} or a site-relative path`,
    })
  }
}

function validateField(value: JsonValue, field: ComponentFieldMetadata, path: string, diagnostics: ComponentDiagnostic[]): void {
  if (field.kind === 'boolean' && typeof value !== 'boolean') {
    diagnostics.push({ severity: 'error', path, message: `${field.label} must be boolean` })
  } else if (field.kind === 'number') {
    if (typeof value !== 'number' || !Number.isFinite(value)) diagnostics.push({ severity: 'error', path, message: `${field.label} must be a finite number` })
    else if ((field.min !== undefined && value < field.min) || (field.max !== undefined && value > field.max)) diagnostics.push({ severity: 'error', path, message: `${field.label} is outside its supported range` })
  } else if ((field.kind === 'string' || field.kind === 'object-reference') && typeof value !== 'string') {
    diagnostics.push({ severity: 'error', path, message: `${field.label} must be text` })
  } else if (field.kind === 'enum' && (typeof value !== 'string' || !field.options?.includes(value))) {
    diagnostics.push({ severity: 'error', path, message: `${field.label} must be one of ${field.options?.join(', ')}` })
  } else if (field.kind === 'color' && (!Array.isArray(value) || value.length !== 3 || value.some((entry) => typeof entry !== 'number' || !Number.isFinite(entry)))) {
    diagnostics.push({ severity: 'error', path, message: `${field.label} must be an RGB number tuple` })
  }
}

function parseTarget(value: unknown, path: string, diagnostics: ComponentDiagnostic[]): PortableComponentTarget | null {
  if (!isRecord(value)) {
    diagnostics.push({ severity: 'error', path, message: 'component target must be an object' })
    return null
  }
  if (value.kind === 'scene') return SCENE_COMPONENT_TARGET
  if (value.kind === 'object') {
    const objectId = stringValue(value.objectId)
    if (!isStableId(objectId)) {
      diagnostics.push({ severity: 'error', path: `${path}.objectId`, message: 'object target needs a stable object ID' })
      return null
    }
    const objectName = typeof value.objectName === 'string' && value.objectName.trim()
      ? value.objectName.trim()
      : undefined
    return { kind: 'object', objectId, ...(objectName ? { objectName } : {}) }
  }
  diagnostics.push({ severity: 'error', path: `${path}.kind`, message: 'target kind must be scene or object' })
  return null
}

function isComponentType(value: string): boolean {
  return /^[a-z][a-z0-9-]*(?:\.[a-z][a-z0-9-]*)+$/.test(value)
}

function isStableId(value: unknown): value is string {
  return typeof value === 'string' && value.trim().length > 0 && value.length <= 256
}

function stringValue(value: unknown): string {
  return typeof value === 'string' ? value.trim() : ''
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return !!value && typeof value === 'object' && !Array.isArray(value)
}

function isJsonObject(value: unknown): value is JsonObject {
  return isJsonValue(value, new WeakSet<object>()) && isRecord(value)
}

/** Reject functions, undefined, non-finite numbers, class instances, and
 * cycles before an export reaches JSON.stringify. */
export function isJsonValue(value: unknown, ancestors = new WeakSet<object>()): value is JsonValue {
  if (value === null || typeof value === 'string' || typeof value === 'boolean') return true
  if (typeof value === 'number') return Number.isFinite(value)
  if (!value || typeof value !== 'object') return false
  if (ancestors.has(value)) return false
  const prototype = Object.getPrototypeOf(value)
  if (prototype !== Object.prototype && prototype !== null && !Array.isArray(value)) return false
  ancestors.add(value)
  const valid = Array.isArray(value)
    ? value.every((entry) => isJsonValue(entry, ancestors))
    : Object.values(value).every((entry) => isJsonValue(entry, ancestors))
  ancestors.delete(value)
  return valid
}
