/**
 * Portable website behaviour contract.
 *
 * Components intentionally describe artist-authored intent rather than an
 * engine implementation.  A Three/Rapier/site adapter may consume a record,
 * but a missing adapter must never make the authored record disappear.
 */

export const PORTABLE_COMPONENT_SCHEMA_VERSION = 1 as const

export type JsonPrimitive = string | number | boolean | null
export type JsonValue = JsonPrimitive | readonly JsonValue[] | { readonly [key: string]: JsonValue }
export type JsonObject = { readonly [key: string]: JsonValue }

/** Object IDs are Blendlink's rename-stable IDs; objectName is only a useful
 * artist-facing diagnostic when a manifest is inspected outside Blender. */
export type PortableComponentTarget =
  | { kind: 'scene' }
  | { kind: 'object'; objectId: string; objectName?: string }

export const SCENE_COMPONENT_TARGET: PortableComponentTarget = { kind: 'scene' }

export interface PortableComponentRecord {
  /** Stable authoring ID. Duplicating an object must create a new component ID. */
  id: string
  /** Namespaced runtime contract, e.g. blendlink.bloom or studio.ripple. */
  type: string
  schemaVersion: typeof PORTABLE_COMPONENT_SCHEMA_VERSION
  enabled: boolean
  target: PortableComponentTarget
  /** Plain JSON only: portable across Blender, glTF, manifests, and adapters. */
  values: JsonObject
}

/** Keep the runtime descriptor additive without making the generic runtime
 * install a component engine. Consumers that import the public component
 * contract see the same descriptor field generated by typegen. */
declare module './runtime.js' {
  interface CompiledSceneDescriptor {
    components?: readonly Readonly<PortableComponentRecord>[] | null
  }
}

export type ComponentTargetKind = PortableComponentTarget['kind']
export type ComponentPortability = 'core' | 'adapter'
export type ComponentLifecyclePhase =
  | 'initial' | 'update' | 'fixed' | 'post-depth' | 'post-hdr' | 'post-ldr'
export type ComponentCardinality = 'one-per-target' | 'many-per-target' | 'one-per-scene'
export type ComponentRuntimeCost = 'free' | 'low' | 'medium' | 'high' | 'very-high'
export type ComponentAdapterKind = 'webgl' | 'tsl'
export type ComponentAdapterSupportLevel = 'production' | 'preview' | 'fallback' | 'unavailable'
export type ComponentRuntimeCapability =
  | 'post-pipeline' | 'hdr-color' | 'depth' | 'normals' | 'velocity'
  | 'camera' | 'raycast' | 'pointer' | 'dom-accessibility'
  | 'animation' | 'audio' | 'physics' | 'scroll-source'

export interface ComponentAdapterSupport {
  webgl: ComponentAdapterSupportLevel
  tsl: ComponentAdapterSupportLevel
}

export interface ComponentFieldMetadata {
  label: string
  description: string
  kind: 'boolean' | 'number' | 'string' | 'color' | 'object-reference' | 'enum'
  default: JsonValue
  min?: number
  max?: number
  options?: readonly string[]
  required?: boolean
}

export interface PortableComponentDefinition {
  id: string
  label: string
  description: string
  category: 'Presentation' | 'Rendering' | 'Interaction' | 'Animation' | 'Audio'
  targets: readonly ComponentTargetKind[]
  portability: ComponentPortability
  /** Definition metadata is authoring/runtime policy and is never serialized
   * into a component record. */
  phase: ComponentLifecyclePhase
  cardinality: ComponentCardinality
  requires: readonly ComponentRuntimeCapability[]
  conflicts: readonly string[]
  cost: ComponentRuntimeCost
  adapters: Readonly<ComponentAdapterSupport>
  fallbacks: Readonly<Partial<Record<ComponentAdapterKind, string>>>
  searchSynonyms: readonly string[]
  consequence: string
  fields: Readonly<Record<string, ComponentFieldMetadata>>
}

export interface ComponentDiagnostic {
  severity: 'error' | 'warning'
  path: string
  message: string
}

export interface ParsePortableComponentsResult {
  components: PortableComponentRecord[]
  diagnostics: ComponentDiagnostic[]
}

