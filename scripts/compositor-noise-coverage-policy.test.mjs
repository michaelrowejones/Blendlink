import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {createHash} from 'node:crypto'
import test from 'node:test'
const read=name=>readFileSync(new URL('../'+name,import.meta.url),'utf8')
const json=name=>JSON.parse(read(name))
const caps=json('docs/node-capabilities.json'),entry=caps.entries['compositor:ShaderNodeTexNoise']
const evidence=json('experiments/compositor-noise-default-field/evidence.json')
const plan=json('experiments/compositor-noise-default-field/cases.json')
const pin=value=>assert.match(value,/^[a-f0-9]{64}$/)

test('Noise classification is CPU5.3-only and preserves independent shader/legacy scopes',()=>{
 assert.equal(entry.category,'unsupported')
 assert.deepEqual(Object.keys(entry.versionOverrides),['5.3.0'])
 assert.equal(entry.versionOverrides['5.3.0'].category,'partial')
 assert.deepEqual(entry.versionOverrides['5.3.0'].modes.noise_dimensions,{partial:['2D'],unsupported:['1D','3D','4D']})
 assert.deepEqual(entry.versionOverrides['5.3.0'].modes.noise_type.partial,['FBM'])
 assert.equal(caps.knownUnsupported.includes('compositor:ShaderNodeTexNoise'),false)
 assert.deepEqual(entry.verification.nativeNumericVersions,['5.3.0'])
 assert.equal(entry.verification.nativeBuild,'02f0899d78e3')
 assert.equal(entry.verification.nativeHost,'darwin-arm64')
 assert.deepEqual(entry.verification.nativeCompositorDevices,['CPU'])
 assert.deepEqual(entry.verification.actualRuntimeBackends,['WebGPU','WebGL2 via WebGPURenderer'])
 assert.deepEqual(entry.verification.actualRuntimeProfiles,['Apple Metal','SwiftShader'])
 const reports=json('docs/node-coverage/coverage.json').reports
 for(const r of reports){
  const compositor=r.domains.compositor.nodes.find(n=>n.id==='ShaderNodeTexNoise')
  if(compositor)assert.equal(compositor.category,r.blenderVersion==='5.3.0'?'partial':'unsupported')
  const shader=r.domains.shader.nodes.find(n=>n.id==='ShaderNodeTexNoise')
  assert.equal(shader.category,'partial')
  assert.equal(shader.enumCoverage.noise_dimensions['4D'],'supported')
  assert.equal(shader.enumCoverage.noise_type.RIDGED_MULTIFRACTAL,'supported')
 }
})

test('Noise evidence keeps measured differences, conjunctive gates and axis-only observations explicit',()=>{
 const v=entry.verification,c=evidence.counts,saved=plan.filter(row=>row.saved)
 assert.equal(plan.length,26);assert.equal(saved.length,8)
 assert.equal(c.nativeGraphs,26);assert.equal(c.nativeOracleControls,15);assert.equal(c.nativeRenders,41)
 assert.equal(c.savedFinalScenes,saved.length);assert.equal(c.browserCaseRuns,4*(plan.length+saved.length))
 assert.equal(c.primaryFloat32Words,4*[...plan,...saved].reduce((n,row)=>n+row.width*row.height*4,0))
 assert.ok(Number.isSafeInteger(c.wordDifferences)&&c.wordDifferences>0&&c.wordDifferences<c.primaryFloat32Words)
 assert.equal(c.wordDifferences,evidence.numericContract.primaryWordDifferences)
 assert.equal(c.contractViolations,0)
 assert.ok(Number.isSafeInteger(c.maxUlps)&&c.maxUlps>=0&&c.maxUlps<=8)
 assert.ok(Number.isFinite(c.maxAbsoluteError)&&c.maxAbsoluteError>=0&&c.maxAbsoluteError<=2**-20)
 assert.equal(c.resizeFrames,8*plan.reduce((n,row)=>n+row.resizeCases.length,0));assert.equal(c.lifecycleCycles,4*saved.length*3)
 assert.equal(evidence.numericContract.combination,'AND')
 assert.equal(evidence.numericContract.bitExactRgb,false)
 assert.deepEqual(evidence.numericContract.gate,{absoluteMax:2**-20,ulpsMax:8})
 assert.deepEqual(evidence.numericContract.exact,['alpha1','scaled Fac lattice0.5','Fac RGB broadcast','Color.red equals Fac'])
 assert.equal(Object.hasOwn(v,'exactWordMismatches'),false)
 for(const [key,value]of Object.entries(c))assert.equal(v[key],value)
 assert.deepEqual(v.numericContract,evidence.numericContract)
 assert.deepEqual(v.axisInstallMeasurements,evidence.axisInstallMeasurements)
 assert.equal(evidence.axisInstallMeasurements.measuredFinalCycles,c.lifecycleCycles)
 assert.equal(v.sourcePolicy.positiveControls,evidence.sourcePolicy.positive.length)
 assert.equal(v.sourcePolicy.namedRefusals,evidence.sourcePolicy.refusals.length)
 for(const key of ['renders','gpuInitializationCalls']){assert.equal(v.sourcePolicy[key],0);assert.equal(evidence.sourcePolicy[key],0)}
 assert.equal(evidence.sourcePolicy.guardControls.renderRefused,true);assert.equal(evidence.sourcePolicy.guardControls.gpuInitializationRefused,true)
 assert.match(evidence.axisInstallMeasurements.scope,/not total CPU\/GPU bytes/)
 assert.equal(evidence.diagnosticHistory.every(row=>row.qualificationCredit===0),true)
 const digest=createHash('sha256').update(read('experiments/compositor-noise-default-field/evidence.json')).digest('hex')
 assert.equal(v.sourceSnapshot.evidenceSha256,digest)
 assert.match(entry.versionOverrides['5.3.0'].limits,/No images?\/scene\/render-pass\/spatial\/mask\/WhiteNoise\/Wave mixtures/)
})

test('Noise current automatic snapshot is consistent and preserves its initial qualification',()=>{
 const snapshot=entry.verification.sourceSnapshot,current=evidence.qualification
 assert.equal(evidence.automaticPipeline.status,'qualified')
 assert.equal(evidence.automaticPipeline.workspaceStable,true)
 assert.equal(evidence.automaticPipeline.productionCredit,true)
 assert.equal(evidence.automaticPipeline.supportPromotion,false)
 assert.match(evidence.sourceCommit,/^[a-f0-9]{40}$/)
 assert.equal(snapshot.sourceCommit,evidence.sourceCommit)
 assert.deepEqual(entry.verification.automaticPipeline,evidence.automaticPipeline)
 pin(current.sha256);assert.deepEqual(snapshot.closedReceipt,{path:current.path,sha256:current.sha256})
 assert.deepEqual(entry.verification.closedReader,current.closedReader)
 pin(current.closedReader.runtimeFingerprint);pin(current.closedReader.verifierSha256)
 assert.equal(evidence.nativeProofs.length,1)
 assert.equal(snapshot.sourceInputs,evidence.nativeProofs[0].sourceInputs)
 assert.equal(snapshot.nativeQualificationSha256,evidence.nativeProofs[0].native.sha256)
 assert.equal(snapshot.finalProofSha256,evidence.nativeProofs[0].final.sha256)
 const history=evidence.history.find(row=>row.path==='experiments/compositor-noise-default-field/history/next45-evidence.json')
 assert.ok(history,'Initial immutable qualification history is required')
 const bytes=read(history.path),initial=JSON.parse(bytes)
 assert.equal(createHash('sha256').update(bytes).digest('hex'),history.sha256)
 assert.equal(history.sha256,'4eba98c4047d5ea04dddaf0198716d4a4385bdb02201e6273876467fefe229ee')
 assert.equal(initial.sourceCommit,'2d8ec4205eadefcc0fd9e9c406bf95157f06ae5e')
 assert.equal(initial.qualification.sha256,'a9c2ca185538f23b35af407f47ed6d127b5df3d268e4e2237e3601b69070a670')
 for(const key of ['nativeGraphs','nativeOracleControls','nativeRenders','savedFinalScenes','browserCaseRuns','primaryFloat32Words','resizeFrames','lifecycleCycles'])assert.equal(initial.counts[key],evidence.counts[key])
})
