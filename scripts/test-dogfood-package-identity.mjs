import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs'
import { basename, dirname, join, resolve } from 'node:path'
import { tmpdir } from 'node:os'
import {
  installContentAddressedLocalPackage,
  packContentAddressedLocalPackage,
  fingerprintPackageTree,
  verifyInstalledLocalPackage,
} from './local-package-identity.mjs'

const tempRoot = mkdtempSync(join(tmpdir(), 'blendlink-local-identity-test-'))

function writeFixture(root, marker) {
  mkdirSync(root, { recursive: true })
  writeFileSync(join(root, 'package.json'), JSON.stringify({
    name: 'blendlink-dogfood-identity-fixture',
    version: '1.0.0',
    files: ['marker.txt'],
  }, null, 2))
  writeFileSync(join(root, 'marker.txt'), `${marker}\n`)
}

function assert(condition, message) {
  if (!condition) throw new Error(message)
}

try {
  const bytecodeTree = join(tempRoot, 'bytecode-tree')
  writeFixture(bytecodeTree, 'stable package bytes')
  const cleanFingerprint = fingerprintPackageTree(bytecodeTree)
  mkdirSync(join(bytecodeTree, '__pycache__'))
  mkdirSync(join(bytecodeTree, 'blender'), { recursive: true })
  writeFileSync(
    join(bytecodeTree, '__pycache__', 'bakelib.cpython-312.pyc'),
    'generated bytecode',
  )
  writeFileSync(join(bytecodeTree, 'blender', 'export_scene.pyc'), 'bytecode')
  writeFileSync(join(bytecodeTree, 'blender', 'legacy.pyo'), 'optimized bytecode')
  assert(
    fingerprintPackageTree(bytecodeTree) === cleanFingerprint,
    'ordinary Python bytecode debris changed installed package identity',
  )
  writeFileSync(join(bytecodeTree, 'blender', 'cache.bin'), 'not Python bytecode')
  assert(
    fingerprintPackageTree(bytecodeTree) !== cleanFingerprint,
    'package identity ignored a non-bytecode file',
  )

  const source = join(tempRoot, 'source')
  const archives = join(tempRoot, 'archives')
  const consumer = join(tempRoot, 'consumer')
  writeFixture(source, 'first compiler')
  mkdirSync(consumer)
  writeFileSync(join(consumer, 'package.json'), JSON.stringify({
    name: 'blendlink-dogfood-identity-consumer',
    version: '1.0.0',
    private: true,
  }, null, 2))

  const first = packContentAddressedLocalPackage(source, archives)
  const firstInstalled = installContentAddressedLocalPackage(
    consumer,
    first.archive,
  )
  assert(
    readFileSync(
      join(consumer, 'node_modules', first.name, 'marker.txt'),
      'utf8',
    ).trim() === 'first compiler',
    'first local compiler archive was not installed',
  )
  assert(
    firstInstalled.installedFingerprint === first.treeFingerprint,
    'first installed tree did not match its archive',
  )

  const devConsumer = join(tempRoot, 'dev-consumer')
  mkdirSync(devConsumer)
  writeFileSync(join(devConsumer, 'package.json'), JSON.stringify({
    name: 'blendlink-dogfood-dev-consumer',
    version: '1.0.0',
    private: true,
    devDependencies: {
      [first.name]: `file:${first.archive.replaceAll('\\', '/')}`,
    },
  }, null, 2))
  const devInstalled = installContentAddressedLocalPackage(
    devConsumer,
    first.archive,
  )
  const devManifest = JSON.parse(
    readFileSync(join(devConsumer, 'package.json'), 'utf8'),
  )
  assert(
    devManifest.dependencies?.[first.name] === undefined &&
      basename(devManifest.devDependencies?.[first.name] ?? '') ===
        basename(first.archive),
    'ordinary npm install did not preserve the existing devDependency section',
  )
  assert(
    devInstalled.installedFingerprint === first.treeFingerprint,
    'devDependency installed tree did not match its archive',
  )

  writeFixture(source, 'second compiler')
  const second = packContentAddressedLocalPackage(source, archives)
  assert(
    first.version === second.version && first.sha256 !== second.sha256,
    'fixture did not produce distinct archives with the same internal version',
  )
  assert(
    basename(first.archive) !== basename(second.archive),
    'different package bytes reused one mutable archive locator',
  )
  const secondInstalled = installContentAddressedLocalPackage(
    consumer,
    second.archive,
  )
  assert(
    readFileSync(
      join(consumer, 'node_modules', second.name, 'marker.txt'),
      'utf8',
    ).trim() === 'second compiler',
    'ordinary npm install retained the stale same-version local compiler',
  )
  assert(
    secondInstalled.installedFingerprint === second.treeFingerprint,
    'second installed tree did not match its archive',
  )

  const lockPath = join(consumer, 'package-lock.json')
  const lock = JSON.parse(readFileSync(lockPath, 'utf8'))
  lock.packages[`node_modules/${second.name}`].integrity =
    'sha512-AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA='
  writeFileSync(lockPath, `${JSON.stringify(lock, null, 2)}\n`)
  let mismatch = ''
  try {
    verifyInstalledLocalPackage(consumer, second.archive)
  } catch (error) {
    mismatch = error instanceof Error ? error.message : String(error)
  }
  assert(
    /root lock integrity .* differs from archive/i.test(mismatch),
    `mismatched root lock was not refused: ${mismatch}`,
  )

  console.log(
    `BLENDLINK_DOGFOOD_PACKAGE_IDENTITY_PASSED ` +
    `${first.sha256.slice(0, 12)} -> ${second.sha256.slice(0, 12)}`,
  )
} finally {
  const resolved = resolve(tempRoot)
  if (
    dirname(resolved) !== resolve(tmpdir()) ||
    !basename(resolved).startsWith('blendlink-local-identity-test-')
  ) {
    throw new Error(`Refusing to remove unexpected test directory ${resolved}.`)
  }
  rmSync(resolved, { recursive: true, force: true })
}
